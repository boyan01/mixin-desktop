#[test]
fn fixed_session_keys_produce_the_same_signatures_as_flutter() {
    // Generated by running the reference bot_signature.dart with Ed25519 seeds
    // 0..31 (account) and 32..63 (bot). These are public test fixtures only.
    let private = (0_u8..32).collect::<Vec<_>>();
    for (method, path, body, expected) in [
        (
            "POST",
            "/web3/swap",
            Some("{\"a\":1}"),
            "NzczZTVlNzctNDEwNy00NWMyLWI2NDgtOGZjNzIyZWQ3N2Y1WRm9g0NEeI4XNYmYyaGIQAWz2u6My3LM0wE0WXnHsmI",
        ),
        (
            "GET",
            "/me",
            Some("  "),
            "NzczZTVlNzctNDEwNy00NWMyLWI2NDgtOGZjNzIyZWQ3N2Y1nESiCUXTnixXKWLg4SyGDqYRmV1-i_XfJ-0sRuy9ads",
        ),
        (
            "GET",
            "/me",
            None,
            "NzczZTVlNzctNDEwNy00NWMyLWI2NDgtOGZjNzIyZWQ3N2Y1nESiCUXTnixXKWLg4SyGDqYRmV1-i_XfJ-0sRuy9ads",
        ),
    ] {
        assert_eq!(
            signature::sign(
                ACCOUNT,
                &private,
                &BOT_PUBLIC,
                1_700_000_000,
                method,
                path,
                body
            )
            .unwrap(),
            expected
        );
    }
}

#[test]
fn malformed_or_noncontributory_keys_cannot_produce_a_signature() {
    let private = [42_u8; 32];
    for public in [[0_u8; 32], {
        let mut point = [0_u8; 32];
        point[0] = 1;
        point
    }] {
        assert!(signature::sign(ACCOUNT, &private, &public, 1, "GET", "/", None).is_err());
    }
    assert!(signature::sign(ACCOUNT, &[0_u8; 31], &BOT_PUBLIC, 1, "GET", "/", None).is_err());
}

#[test]
fn signatures_require_the_verified_window_app_and_its_native_page_resource() {
    let mut user = app_user();
    assert!(signing_allowed(&user, APP, "https://bot.example/app/page"));
    user.is_verified = false;
    assert!(!signing_allowed(&user, APP, "https://bot.example/app"));
    user.is_verified = true;
    user.app.as_mut().unwrap().app_id = ACCOUNT.into();
    assert!(!signing_allowed(&user, APP, "https://bot.example/app"));
    user.app.as_mut().unwrap().app_id = APP.into();
    user.user_id = ACCOUNT.into();
    assert!(!signing_allowed(&user, APP, "https://bot.example/app"));
    user.user_id = APP.into();
    assert!(!signing_allowed(&user, APP, "https://other.example/app"));
    user.app = None;
    assert!(!signing_allowed(&user, APP, "https://bot.example/app"));
}

#[test]
fn resource_matching_preserves_path_prefix_rules_and_requires_the_same_origin() {
    let patterns = vec![" HTTPS://BOT.EXAMPLE:443/app ".into()];
    for (url, allowed) in [
        ("https://bot.example/app/page?q=1", true),
        ("https://bot.example/application", true),
        ("https://bot.example/app", true),
        ("https://bot.example:443/app", true),
        ("https://bot.example/other", false),
        ("https://bot.example:444/app", false),
        ("http://bot.example/app", false),
        ("https://bot.example.evil/app", false),
        ("https://attacker@bot.example/app", false),
        ("https://bot.example/app/../other", false),
        ("file:///app", false),
    ] {
        assert_eq!(
            signature::matches_resource(url, &patterns),
            allowed,
            "{url}"
        );
    }
    assert!(!signature::matches_resource(
        "https://bot.example/app",
        &["invalid".into()]
    ));
}

#[test]
fn bot_public_keys_accept_both_wire_base64url_encodings_and_reject_wrong_lengths() {
    assert_eq!(
        decode_public_key(&Base64Url::encode_string(&BOT_PUBLIC)).unwrap(),
        BOT_PUBLIC
    );
    assert_eq!(
        decode_public_key(&Base64UrlUnpadded::encode_string(&BOT_PUBLIC)).unwrap(),
        BOT_PUBLIC
    );
    assert!(decode_public_key("not a key").is_err());
    assert!(decode_public_key(&Base64UrlUnpadded::encode_string(&[7_u8; 31])).is_err());
}

#[tokio::test]
async fn bot_context_only_accepts_current_account_conversations_and_joined_groups() {
    let directory = tempfile::tempdir().unwrap();
    let database = MixinDatabase::connect_at(directory.path().join("mixin.db"))
        .await
        .unwrap();
    let direct = generate_conversation_id(ACCOUNT, APP).to_string();
    for (id, owner, category, status) in [
        (direct.as_str(), APP, "CONTACT", 2),
        ("mismatched-direct", APP, "CONTACT", 2),
        ("joined", ACCOUNT, "GROUP", 2),
        ("quit", ACCOUNT, "GROUP", 3),
        ("other-member", ACCOUNT, "GROUP", 2),
    ] {
        database
            .conversation_dao
            .insert(&Conversation {
                conversation_id: id.into(),
                owner_id: Some(owner.into()),
                category: Some(if category == "GROUP" {
                    ConversationCategory::Group
                } else {
                    ConversationCategory::Contact
                }),
                name: String::new(),
                icon_url: String::new(),
                announcement: String::new(),
                code_url: String::new(),
                created_at: Utc::now(),
                status: ConversationStatus(status),
                mute_until: chrono::DateTime::UNIX_EPOCH,
                expire_in: 0,
            })
            .await
            .unwrap();
    }
    for (id, member) in [
        ("joined", ACCOUNT),
        ("quit", ACCOUNT),
        ("other-member", APP),
    ] {
        database
            .participant_dao
            .replace_all(
                id,
                &[Participant {
                    conversation_id: id.into(),
                    user_id: member.into(),
                    role: None,
                    created_at: Utc::now(),
                }],
            )
            .await
            .unwrap();
    }
    assert!(validate_source(&database, ACCOUNT, None).await.is_ok());
    let direct_result = validate_source(&database, ACCOUNT, Some(&direct)).await;
    assert!(direct_result.is_ok(), "{direct_result:?}");
    assert!(validate_source(&database, ACCOUNT, Some("joined"))
        .await
        .is_ok());
    for id in ["mismatched-direct", "quit", "other-member", "missing", ""] {
        assert!(
            validate_source(&database, ACCOUNT, Some(id)).await.is_err(),
            "{id}"
        );
    }
    assert!(validate_source(&database, APP, Some(&direct))
        .await
        .is_err());
}

#[test]
fn forwarding_a_bot_resource_rebuilds_the_card_and_external_pages_remain_links() {
    let app = app_user().app.unwrap();
    let card = shared_page_card(&app, "https://bot.example/app/item", "  Page title  ").unwrap();
    assert_eq!(card["app_id"], APP);
    assert_eq!(card["title"], "Bot");
    assert_eq!(card["description"], "Page title");
    assert_eq!(card["action"], "https://bot.example/app/item");
    assert_eq!(card["shareable"], true);
    assert_eq!(
        shared_page_card(&app, "https://bot.example/app", " ").unwrap()["description"],
        "Bot"
    );
    assert!(shared_page_card(&app, "https://external.example/app", "Page").is_none());
    assert!(shared_page_card(&app, "https://user@bot.example/app", "Page").is_none());
}
